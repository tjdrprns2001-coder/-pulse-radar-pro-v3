'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {analyzeTrades,getFlow,observe}=require('../lib/market-intel/aggressive-trade-flow.js');
const handler=require('../handlers/agg-trade-flow.js');
const rows=Array.from({length:80},(_,i)=>({a:i,T:1700000000000+i*1000,p:String(100+i*.001),q:'2',m:i<65}));
const flow=analyzeTrades(rows,{market:'futures',symbol:'BTCUSDT',now:1700000100000});
assert.equal(flow.available,true);
assert.equal(flow.tradeCount,80);
assert(flow.sellNotional>flow.buyNotional);
assert(flow.netDeltaNotional<0);
assert.equal(flow.possibleAbsorption,'POSSIBLE_BUY_ABSORPTION');
assert.equal(flow.cvdAvailable,undefined,'do not claim persistent full-history CVD');
assert(flow.partialWindow);
assert.equal(flow.source,'BINANCE_AGG_TRADES');
assert.equal(flow.points[0].cvd<0,true);
assert.equal(analyzeTrades(rows.slice(0,8),{symbol:'BTCUSDT'}).available,false);
assert.equal(analyzeTrades([], {symbol:'BTCUSDT'}).reason,'NO_TRADES');
assert.equal(analyzeTrades(rows.slice().reverse(),{market:'futures',symbol:'BTCUSDT'}).cvdEnd,flow.cvdEnd);
(async()=>{
 let requested='';
 const live=await getFlow({symbol:'BTCUSDT',market:'futures',fetchImpl:async url=>{if(url.includes('aggTrades'))requested=url;return{ok:true,json:async()=>url.includes('aggTrades')?rows:{bids:[],asks:[]}}}});
 assert.equal(live.available,true);assert(requested.startsWith('https://fapi.binance.com/fapi/v1/aggTrades?'));
 const sampleDepth={bids:[['100','3'],['99','2']],asks:[['101','1'],['102','1']]};
 const snap=observe('futures:UNITTESTUSDT',rows,sampleDepth,1700000100000);
 assert.equal(snap.rolling.newTrades,80);
 assert(snap.depth.available&&snap.depth.imbalance>0);
 const again=observe('futures:UNITTESTUSDT',rows,sampleDepth,1700000102000);
 assert.equal(again.rolling.newTrades,0,'repeated poll must not double-count CVD');
 assert.equal(again.rolling.netDeltaNotional,snap.rolling.netDeltaNotional);
 const newer=[{a:81,T:1700000102000,p:'101',q:'1',m:false}];
 const more=observe('futures:UNITTESTUSDT',newer,null,1700000102000);
 assert.equal(more.rolling.newTrades,1);
 assert.equal(more.depth.available,false);
 assert.equal(more.rolling.ephemeral,true,'not durable storage');

 const bad=await getFlow({symbol:'../PRIVATE',market:'futures',fetchImpl:async()=>{throw Error('must not be called')}});
 assert.equal(bad.ok,false);
 const fail=await getFlow({symbol:'BTCUSDT',market:'spot',fetchImpl:async()=>{throw Error('private network')}});
 assert.equal(fail.available,false);assert.equal(fail.reason,'TRADE_FETCH_FAILED');
 let status=0,out=null;
 const res={setHeader(){},status(n){status=n;return this},json(x){out=x;return x}};
 await handler({method:'GET',query:{symbol:'BTCUSDT',market:'futures'}},res,{getFlowImpl:async()=>live});
 assert.equal(status,200);assert.equal(out.tradeCount,80);
 const html=fs.readFileSync('auto-chart-lab.html','utf8');
 assert(html.includes('id="cardCvd"')&&html.includes('id="cardAbsorption"'));
 assert(fs.readFileSync('ui/auto-chart/data/market-data.js','utf8').includes('fetchTradeFlow'));
 console.log('Binance sampled aggTrades CVD, taker sign, missing data, API and chart wiring PASS');
})().catch(e=>{console.error(e);process.exitCode=1});
