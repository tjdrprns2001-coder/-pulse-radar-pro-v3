'use strict';
const assert=require('assert');
const Evidence=require('../lib/signal-performance/evidence.js');
const Core=require('../lib/coin-scan/scanner-core.js');
const NOW=10_000_000;
assert.throws(()=>Evidence.normalizeEvidence({title:'x',publishedAt:NOW}),/url/i);
const official=Evidence.normalizeEvidence({title:'Protocol upgrade',url:'https://example.org/a',domain:'example.org',publishedAt:NOW-1000,symbols:['AAAUSDT'],type:'official-project',direction:'positive'});
const duplicate={...official,title:'Protocol upgrade copied'};
const negative=Evidence.normalizeEvidence({title:'Upgrade delayed',url:'https://news.example/b',domain:'news.example',publishedAt:NOW-2000,symbols:['AAAUSDT'],type:'news',direction:'negative'});
const stale=Evidence.normalizeEvidence({title:'Old item',url:'https://old.example/c',domain:'old.example',publishedAt:NOW-30_000_000,symbols:['AAAUSDT'],type:'news'});
const ranked=Evidence.rankEvidence([official,duplicate,negative,stale],{now:NOW,ttlMs:6*60*60*1000});
assert.equal(ranked.sources,2,'duplicate and stale evidence must not inflate source count');
assert.equal(ranked.strength,'strong','fresh official source should support strong evidence');
assert(ranked.items.some(x=>x.conflict===true),'opposing evidence must be retained as conflict');
const noMeta=Core.classifyV2({dataState:'live',priceChange24h:1,structure:'neutral',volumeAcceleration15m:1,takerRatio:1});
assert.notEqual(noMeta.key,'META-PRE');
const withMeta=Core.classifyV2({dataState:'live',priceChange24h:1,structure:'neutral',volumeAcceleration15m:1,takerRatio:1,metaEvidence:ranked});
assert.equal(withMeta.key,'META-PRE');
console.log('signal evidence contract PASS');
