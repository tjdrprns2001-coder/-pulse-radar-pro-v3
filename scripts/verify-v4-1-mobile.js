assert(Array.isArray(vercel.headers)&&vercel.headers.some(x=>x.source==='/(.*).html')&&vercel.headers.some(x=>x.source==='/ui/(.*)'),'stale V3 cache prevention headers missing');
assert.deepEqual(vercel.regions,['icn1'],'Seoul Vercel region must remain pinned');
